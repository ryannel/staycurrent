#!/usr/bin/env python3
"""Disposable PostgreSQL 18 cutover worksheet. Python 3 standard library only.

Run as a non-root OS user:
  python3 rehearse.py --pg-bin /path/to/postgresql-18/bin --evidence ./move.json
Requires initdb, pg_ctl, psql, pg_dump and pg_restore from PostgreSQL 18.
Creates two NEW local trust-authenticated clusters, never contacts an existing
service. Only invented orders. All commands and waits are bounded. Evidence is
created exclusively and includes commands, SQL, outputs, timings and server logs.
No production-scale acceptance or universal production fence is claimed.
"""
import argparse
import json
import os
from pathlib import Path
import shutil
import socket
import subprocess
import tempfile
import time


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--pg-bin', required=True)
    parser.add_argument('--evidence', required=True)
    args = parser.parse_args()
    evidence_path = Path(args.evidence).resolve()
    # Reserve the destination before allocating resources; never overwrite it.
    evidence_file = evidence_path.open('x', encoding='utf-8')
    work = Path(tempfile.mkdtemp(prefix='a31-cutover-'))
    record = {'scope': 'Invented orders; PostgreSQL logical and paused moves',
              'commands': [], 'observations': {}, 'cleanup': {}}
    started = []
    processes = []
    ports = {}
    env = os.environ.copy()
    # Ignore caller libpq configuration for this wholly local fixture.
    for key in list(env):
        if key.startswith('PG'):
            env.pop(key)
    env.update(PGCONNECT_TIMEOUT='3', PGOPTIONS='-c statement_timeout=8000 -c lock_timeout=2000', LC_ALL='C')

    def run(tool, argv=(), sql=None, expected=0, timeout=20):
        command = [str(Path(args.pg_bin) / tool), *map(str, argv)]
        before = time.monotonic()
        result = subprocess.run(command, input=sql, text=True, capture_output=True,
                                env=env, timeout=timeout)
        record['commands'].append({'command': command, 'sql': sql,
            'exit': result.returncode, 'stdout': result.stdout, 'stderr': result.stderr,
            'seconds': round(time.monotonic() - before, 6)})
        if expected is not None and result.returncode != expected:
            raise AssertionError(f'{tool} exit {result.returncode}: {result.stderr}')
        return result

    def sql(side, database, statement, role='drill', expected=0):
        return run('psql', ['-X', '-At', '-h', '127.0.0.1', '-p', ports[side],
            '-U', role, '-d', database, '-v', 'ON_ERROR_STOP=1', '-v', 'VERBOSITY=verbose'],
            statement, expected).stdout.strip()

    def check(label, condition, detail):
        record['observations'][label] = detail
        if not condition:
            raise AssertionError(label)

    def wait_for(label, probe, seconds=12):
        end = time.monotonic() + seconds
        while time.monotonic() < end:
            if probe():
                return
            time.sleep(.1)
        raise AssertionError(f'Deadline: {label}')

    def allocate():
        with socket.socket() as sock:
            sock.bind(('127.0.0.1', 0))
            return sock.getsockname()[1]

    def begin_sleeper(database, role, statement):
        command = [str(Path(args.pg_bin) / 'psql'), '-X', '-At', '-h', '127.0.0.1',
                   '-p', str(ports['source']), '-U', role, '-d', database,
                   '-v', 'ON_ERROR_STOP=1', '-v', 'VERBOSITY=verbose']
        process = subprocess.Popen(command, stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                                   stderr=subprocess.PIPE, text=True, env=env)
        processes.append(process)
        process.stdin.write(statement)
        process.stdin.close()
        process.stdin = None
        wait_for('sleeper visible', lambda: sql('source', database,
            f"SELECT count(*) FROM pg_stat_activity WHERE usename='{role}' AND wait_event='PgSleep';") == '1')
        return process, command, statement

    def finish_sleeper(item):
        process, command, statement = item
        stdout, stderr = process.communicate(timeout=12)
        record['commands'].append({'command': command, 'sql': statement,
            'exit': process.returncode, 'stdout': stdout, 'stderr': stderr})
        return process.returncode

    schema = """
CREATE TABLE orders (
 id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 101) PRIMARY KEY,
 reference text COLLATE "C" NOT NULL UNIQUE,
 status text NOT NULL CHECK (status IN ('pending','paid')),
 total integer NOT NULL CHECK (total >= 0),
 placed_at timestamptz NOT NULL DEFAULT current_timestamp
);
CREATE TABLE items (
 order_id bigint REFERENCES orders ON DELETE CASCADE,
 line integer NOT NULL, quantity integer NOT NULL CHECK(quantity > 0),
 unit_price integer NOT NULL CHECK(unit_price >= 0), PRIMARY KEY(order_id,line)
);
CREATE TABLE move_boundary (token text PRIMARY KEY);
INSERT INTO orders(reference,status,total)
 SELECT 'R'||n, 'pending', 100 FROM generate_series(1,2000) n;
INSERT INTO items SELECT id,1,1,100 FROM orders;
"""
    def grant(side, database, role):
        sql(side, database, f"GRANT SELECT,INSERT,UPDATE,DELETE ON orders,items TO {role}; GRANT USAGE ON SEQUENCE orders_id_seq TO {role};")

    def reconcile(database):
        output = {}
        for side in ['source', 'destination']:
            output[side] = {table: sql(side, database, query) for table, query in {
                'orders': 'SELECT id,reference,status,total,placed_at FROM orders ORDER BY id;',
                'items': 'SELECT * FROM items ORDER BY order_id,line;',
                'boundary': 'SELECT * FROM move_boundary ORDER BY token;'}.items()}
        return output, output['source'] == output['destination']

    try:
        record['version'] = run('postgres', ['--version']).stdout.strip()
        if ' 18.' not in record['version']:
            raise AssertionError('PostgreSQL 18 binaries required')
        for side in ['source', 'destination']:
            ports[side] = allocate()
            directory = work / side
            run('initdb', ['-D', directory, '--username=drill', '--locale=C', '--encoding=UTF8',
                          '--auth-local=trust', '--auth-host=trust'])
            with (directory / 'postgresql.conf').open('a') as config:
                config.write(f"\nlisten_addresses='127.0.0.1'\nport={ports[side]}\nunix_socket_directories='{work}'\n"
                    "wal_level=logical\nmax_replication_slots=8\nmax_wal_senders=8\n"
                    "max_connections=16\nshared_buffers='32MB'\nmax_worker_processes=6\n"
                    "max_logical_replication_workers=4\nmax_sync_workers_per_subscription=2\n"
                    "max_parallel_workers=0\nmax_parallel_apply_workers_per_subscription=0\n"
                    "timezone='UTC'\nlog_min_messages=warning\n")
            # Track before start, so cleanup also covers a partially successful start.
            started.append(side)
            run('pg_ctl', ['-D', directory, '-l', work / f'{side}.log', '-w', '-t', '15', 'start'])
            sql(side, 'postgres', 'CREATE DATABASE online;')
            sql(side, 'postgres', 'CREATE DATABASE paused;')
            sql(side, 'postgres', 'CREATE ROLE move_app LOGIN; CREATE ROLE pause_app LOGIN;')
        record['environment'] = {side: sql(side, 'postgres',
            "SELECT version(); SHOW fsync; SHOW synchronous_commit; SHOW full_page_writes; SHOW wal_level; SHOW TimeZone;") for side in ports}

        # Complete write-pause route: no live change stream.
        sql('source', 'paused', schema)
        grant('source', 'paused', 'pause_app')
        sql('source', 'paused', 'ALTER ROLE pause_app NOLOGIN; REVOKE INSERT,UPDATE,DELETE ON orders,items FROM pause_app;')
        sql('source', 'paused', "INSERT INTO move_boundary VALUES('paused-final');")
        pause_start = time.monotonic()
        archive = work / 'paused.dump'
        run('pg_dump', ['-h','127.0.0.1','-p',ports['source'],'-U','drill','-d','paused',
                        '-Fc','--no-owner','--no-acl','-f',archive])
        run('pg_restore', ['-h','127.0.0.1','-p',ports['destination'],'-U','drill','-d','paused',
                           '--single-transaction','--exit-on-error',archive])
        comparison, equal = reconcile('paused')
        check('paused_rows_equal', equal, {'equal':equal,'orders':2000,'items':2000})
        # Failed restore gate: a repeated load is refused, not accepted as complete.
        failed = run('pg_restore', ['-h','127.0.0.1','-p',ports['destination'],'-U','drill','-d','paused',
                     '--single-transaction','--exit-on-error',archive], expected=None)
        check('repeated_restore_refused', failed.returncode != 0, failed.stderr)
        grant('destination', 'paused', 'pause_app')
        accepted = sql('destination','paused', "INSERT INTO orders(reference,status,total) VALUES('after-pause','paid',100) RETURNING id;", role='pause_app')
        check('paused_generated_id', accepted.splitlines()[0]=='2101', accepted)
        record['observations']['paused_seconds'] = round(time.monotonic()-pause_start,6)

        # Shorter final pause: use the built-in snapshot/change-stream join.
        sql('source', 'online', schema)
        grant('source','online','move_app')
        definitions = run('pg_dump',['-h','127.0.0.1','-p',ports['source'],'-U','drill','-d','online',
                                    '--schema-only','--no-owner','--no-acl']).stdout
        sql('destination','online',definitions)
        sql('source','online','CREATE PUBLICATION move_pub FOR TABLE orders,items,move_boundary;')
        copy_start = time.monotonic()
        sql('destination','online',f"CREATE SUBSCRIPTION move_sub CONNECTION 'host=127.0.0.1 port={ports['source']} user=drill dbname=online' PUBLICATION move_pub WITH (copy_data=true,streaming=off,synchronous_commit=on);")
        # Change immediately after starting copy; membership/order joins are engine-owned.
        sql('source','online',"BEGIN; UPDATE orders SET status='paid',total=200 WHERE id=101; UPDATE items SET quantity=2 WHERE order_id=101; DELETE FROM orders WHERE id=102; INSERT INTO orders(reference,status,total) VALUES('during-copy','pending',100); INSERT INTO items SELECT id,1,1,100 FROM orders WHERE reference='during-copy'; COMMIT;")
        ready_query="SELECT count(*)=3 AND bool_and(srsubstate='r') FROM pg_subscription_rel WHERE srsubid=(SELECT oid FROM pg_subscription WHERE subname='move_sub');"
        wait_for('all three tables ready',lambda: sql('destination','online',ready_query)=='t')
        wait_for('changes applied',lambda: sql('destination','online',"SELECT status||':'||total FROM orders WHERE id=101;")=='paid:200')
        record['observations']['initial_sync_seconds'] = round(time.monotonic()-copy_start,6)

        # NOLOGIN alone leaves an already connected writer alive.
        old = begin_sleeper('online','move_app',"BEGIN; SELECT pg_sleep(1); INSERT INTO orders(reference,status,total) VALUES('old-pool','pending',100); COMMIT;")
        sql('source','online','ALTER ROLE move_app NOLOGIN;')
        check('existing_session_survives_nologin',finish_sleeper(old)==0,
              sql('source','online',"SELECT reference FROM orders WHERE reference='old-pool';"))
        sql('source','online',"INSERT INTO items SELECT id,1,1,100 FROM orders WHERE reference='old-pool'; ALTER ROLE move_app LOGIN;")
        # Terminate an in-flight uncommitted write and verify its rollback.
        pending = begin_sleeper('online','move_app',"BEGIN; INSERT INTO orders(reference,status,total) VALUES('uncommitted','pending',100); SELECT pg_sleep(5); COMMIT;")
        final_start=time.monotonic()
        sql('source','online',"ALTER ROLE move_app NOLOGIN; REVOKE INSERT,UPDATE,DELETE ON orders,items FROM move_app; REVOKE USAGE ON SEQUENCE orders_id_seq FROM move_app;")
        sql('source','online',"SELECT pg_terminate_backend(pid) FROM pg_stat_activity WHERE usename='move_app';")
        check('inflight_terminated',finish_sleeper(pending)!=0,True)
        check('inflight_absent',sql('source','online',"SELECT count(*) FROM orders WHERE reference='uncommitted';")=='0',True)
        denied = run('psql',['-X','-h','127.0.0.1','-p',ports['source'],'-U','move_app','-d','online','-c','SELECT 1'],expected=None)
        check('fresh_source_connection_denied',denied.returncode!=0,denied.stderr)
        # Prove a lagging final marker closes the gate; restart and catch up.
        sql('destination','online','ALTER SUBSCRIPTION move_sub DISABLE;')
        wait_for('apply worker stopped',lambda: sql('destination','online',"SELECT count(*) FROM pg_stat_subscription WHERE subname='move_sub' AND pid IS NOT NULL;")=='0')
        sql('source','online',"SELECT setval('orders_id_seq',5000,true); INSERT INTO move_boundary VALUES('online-final');")
        check('disabled_apply_marker_absent',sql('destination','online',"SELECT count(*) FROM move_boundary WHERE token='online-final';")=='0',True)
        sql('destination','online','ALTER SUBSCRIPTION move_sub ENABLE;')
        wait_for('final marker applied',lambda:sql('destination','online',"SELECT count(*) FROM move_boundary WHERE token='online-final';")=='1')
        check('relations_ready_at_boundary',sql('destination','online',ready_query)=='t',True)
        # Freeze destination apply after the complete scoped boundary; keep source fenced.
        sql('destination','online','ALTER SUBSCRIPTION move_sub DISABLE;')
        wait_for('apply quiescent',lambda:sql('destination','online',"SELECT count(*) FROM pg_stat_subscription WHERE subname='move_sub' AND pid IS NOT NULL;")=='0')
        comparison,equal=reconcile('online')
        check('online_full_comparison_equal',equal,comparison)
        sql('destination','online','UPDATE orders SET total=999 WHERE id=103;')
        comparison,equal=reconcile('online')
        check('equal_counts_hide_wrong_value',not equal and sql('source','online','SELECT count(*) FROM orders;')==sql('destination','online','SELECT count(*) FROM orders;'), {'equal':equal,'bad_order':103})
        sql('destination','online','UPDATE orders SET total=100 WHERE id=103;')
        _,equal=reconcile('online')
        check('repaired_comparison_equal',equal,True)
        invariant="SELECT count(*) FROM orders o WHERE total<>(SELECT coalesce(sum(quantity*unit_price),0) FROM items WHERE order_id=o.id);"
        check('domain_invariant',sql('destination','online',invariant)=='0',True)
        # Sequence state is independent of rows and did not replicate.
        before=sql('destination','online','SELECT last_value,is_called FROM orders_id_seq;')
        collision=run('psql',['-X','-h','127.0.0.1','-p',ports['destination'],'-U','drill','-d','online','-v','ON_ERROR_STOP=1','-v','VERBOSITY=verbose'],"INSERT INTO orders(reference,status,total) VALUES('unsafe-id','paid',100);",expected=None)
        check('unsynchronised_sequence_collision',collision.returncode!=0 and '23505' in collision.stderr,{'state_before':before,'error':collision.stderr})
        source_seq=sql('source','online','SELECT last_value,is_called FROM orders_id_seq;')
        value,called=source_seq.split('|')
        sql('destination','online',f"SELECT setval('orders_id_seq',{int(value)},{'true' if called=='t' else 'false'});")
        check('sequence_state_equal',sql('destination','online','SELECT last_value,is_called FROM orders_id_seq;')==source_seq,source_seq)
        sql('destination','online','ANALYZE orders; ANALYZE items;')
        # New fresh application connections, only after the gates pass.
        grant('destination','online','move_app')
        new_id=sql('destination','online',"BEGIN; INSERT INTO orders(reference,status,total) VALUES('destination-only','paid',100) RETURNING id; INSERT INTO items SELECT id,1,1,100 FROM orders WHERE reference='destination-only'; COMMIT;",role='move_app')
        check('destination_committed_new_order','5001' in new_id.splitlines(),new_id)
        check('source_lacks_destination_write',sql('source','online',"SELECT count(*) FROM orders WHERE reference='destination-only';")=='0',True)
        bad=run('psql',['-X','-h','127.0.0.1','-p',ports['destination'],'-U','move_app','-d','online','-v','ON_ERROR_STOP=1','-v','VERBOSITY=verbose'],"INSERT INTO orders(reference,status,total) VALUES('negative','paid',-1);",expected=None)
        check('application_constraint_rejected',bad.returncode!=0 and '23514' in bad.stderr,bad.stderr)
        check('application_read',sql('destination','online',"SELECT status,total FROM orders WHERE reference='destination-only';",role='move_app')=='paid|100',True)
        record['observations']['final_drill_seconds']=round(time.monotonic()-final_start,6)
        record['observations']['final_boundary']='online-final; three ready relations; source app fenced; exact row comparison; sequence 5000|t'
        sql('destination','online','DROP SUBSCRIPTION move_sub;')
        check('slot_removed',sql('source','online',"SELECT count(*) FROM pg_replication_slots WHERE slot_name='move_sub';")=='0',True)
        record['result']='passed'
    except BaseException as error:
        record['result']='failed'
        record['error']=repr(error)
        raise
    finally:
        for process in processes:
            if process.poll() is None:
                process.kill()
                process.wait(timeout=5)
        cleanup_ok=True
        for side in reversed(started):
            try:
                result=run('pg_ctl',['-D',work/side,'-m','fast','-w','-t','15','stop'],expected=None)
                status=run('pg_ctl',['-D',work/side,'status'],expected=None)
                stopped=status.returncode==3
                record['cleanup'][side]={'stop_exit':result.returncode,'status_exit':status.returncode,'stopped':stopped}
                cleanup_ok=cleanup_ok and stopped
            except BaseException as error:
                cleanup_ok=False
                record['cleanup'][side]={'error':repr(error)}
        record['logs']={side:(work/f'{side}.log').read_text(errors='replace') for side in started if (work/f'{side}.log').exists()}
        if cleanup_ok:
            shutil.rmtree(work)
        record['cleanup']['temporary_directory_removed']=not work.exists()
        json.dump(record,evidence_file,indent=2)
        evidence_file.write('\n')
        evidence_file.close()
        print(f"{record['result']}: {evidence_path}")


if __name__=='__main__':
    main()
