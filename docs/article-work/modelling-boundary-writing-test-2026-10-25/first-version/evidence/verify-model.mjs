import assert from 'node:assert/strict';
import { lines, orders, offers, total, paymentTotal, wrongJoinedTotals, reconstructedOffers, repricedTotal, tags, suppliers, explanations } from '../src/components/modelling-first-draft/model.mjs';
const unique = rows => [...new Map(rows.map(r => [JSON.stringify(r), r])).values()];
const selected = lines.filter(l => l.order === 101 || l.order === 103);
const originalAssociations = selected.map(l => [l.order, 1, l.product]);
const orderCustomer = unique(originalAssociations.map(([o,c]) => [o,c]));
const customerProduct = unique(originalAssociations.map(([,c,p]) => [c,p]));
const unsafe = orderCustomer.flatMap(([o,c])=>customerProduct.filter(([cc])=>c===cc).map(([,p])=>[o,c,p]));
const unsafeExtra=unsafe.filter(row=>!originalAssociations.some(r=>r.every((v,i)=>row[i]===v)));
const safe = selected.map(l=>({ ...l, customer: orders.find(o=>o.id===l.order).customer, placed: orders.find(o=>o.id===l.order).placed }));
assert.equal(safe.length, selected.length);
assert.deepEqual(safe.map(({customer, placed, ...l})=>l),selected);
assert.deepEqual([total(101),total(102),total(103)],[39.5,40,29]);
assert.equal(paymentTotal(101),39.5);
assert.equal(paymentTotal(103),0);
assert.deepEqual(wrongJoinedTotals(101),{lines:79,payments:79});
assert.deepEqual(unsafeExtra,[[101,1,'P7'],[103,1,'P9']]);
const reconstructed = reconstructedOffers();
const extra = reconstructed.filter(r=>!offers.some(o=>o.every((v,i)=>v===r[i])));
assert.equal(reconstructed.length,4);
assert.deepEqual(extra,[['S1','P7','North']]);
assert.equal(tags.length*suppliers.length,4);
assert.equal((tags.length+1)*suppliers.length,6);
assert.equal(repricedTotal(103),31);
assert.equal(total(103),29);
assert.equal(explanations.normalise.length,4);
assert.equal(explanations.offers.length,4);
console.log(JSON.stringify({node:process.version,scope:'Pure illustrative calculations; no database engine',coreTotals:[total(101),total(102),total(103)],payment101:paymentTotal(101),wrongJoinedTotals:wrongJoinedTotals(101),safeLineCount:safe.length,unsafeExtra,offerExtra:extra,independentCombinations:tags.length*suppliers.length,withThirdTag:(tags.length+1)*suppliers.length,agreedTotal103:total(103),wrongRepricedTotal103:repricedTotal(103),result:'passed'},null,2));
