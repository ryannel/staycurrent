import {PGlite} from '@electric-sql/pglite';
import fs from 'node:fs';
import assert from 'node:assert/strict';
import * as queries from '../src/components/relational-rebuild-query-results/queries.mjs';
const db = new PGlite();
try {
 const version=(await db.query('SELECT version()')).rows;
 const exactDownload = fs.readFileSync('public/relational-rebuild/query-results/shop-queries.sql','utf8');
 const result=await db.exec(exactDownload);
 fs.writeFileSync('evidence/pglite-download-results.json',JSON.stringify({version,result},null,2));
 await db.exec(fs.readFileSync('evidence/setup.sql','utf8'));
 const output={version};
 for (const [name,sql] of Object.entries(queries)) output[name]=(await db.query(sql)).rows;
 assert.equal(output.customerJoin.length,3);
 assert.equal(output.lineJoin.length,5);
 assert.equal(output.leftJoin.length,4);
 assert.equal(output.onCard.length,3);
 assert.equal(output.whereCard.length,2);
 assert.deepEqual(output.existsOrders.map(r=>r.customer_id),[1,2]);
 assert.deepEqual(output.noOrders.map(r=>r.customer_id),[3]);
 assert.deepEqual(output.noPayments.map(r=>r.order_id),[103]);
 assert.equal(output.rawJoin.length,4);
 assert.equal(Number(output.badTotals[0].line_total),79);
 assert.equal(Number(output.badTotals[0].paid_total),79);
 assert.deepEqual(output.allBalances.map(r=>Number(r.due)),[0,0,29]);
 assert.deepEqual(output.report.map(r=>[r.order_id,Number(r.due)]),[[103,29]]);
 assert.deepEqual(output.unionAll.map(r=>r.customer_id),[1,1,2]);
 assert.deepEqual(output.union.map(r=>r.customer_id),[1,2]);
 assert.deepEqual(output.intersect.map(r=>r.customer_id),[1]);
 assert.deepEqual(output.except.map(r=>r.customer_id),[2]);
 output.noCoalesce=(await db.query(queries.report.replaceAll('COALESCE(p.paid_total, 0)','p.paid_total'))).rows;
 assert.equal(output.noCoalesce.length,0);
 await db.exec('SAVEPOINT equal_lines; UPDATE order_items SET quantity=1 WHERE order_id=102; INSERT INTO order_items VALUES (102,2,\'P7\',1,20.00);');
 output.equalLines=(await db.query('SELECT SUM(quantity*unit_price) AS correct, SUM(DISTINCT quantity*unit_price) AS wrong FROM order_items WHERE order_id=102')).rows;
 assert.deepEqual(output.equalLines.map(r=>[Number(r.correct),Number(r.wrong)]),[[40,20]]);
 await db.exec("ROLLBACK TO equal_lines; INSERT INTO payments VALUES (504,103,10.00,'card');");
 output.partialReport=(await db.query(queries.report)).rows;
 output.partialNoPayments=(await db.query(queries.noPayments)).rows;
 assert.deepEqual(output.partialReport.map(r=>[r.order_id,Number(r.due)]),[[103,19]]);
 assert.equal(output.partialNoPayments.length,0);
 await db.exec('ROLLBACK;');
 fs.writeFileSync('evidence/pglite-asserted-results.json',JSON.stringify(output,null,2));
 console.log(JSON.stringify({version,checks:'All exact-download execution and assertion checks passed; database closed in finally.'}));
} finally { await db.close(); }
