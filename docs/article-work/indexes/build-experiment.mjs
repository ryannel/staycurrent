// Writes experiment.sql from the commands the Indexes article displays,
// so the download always matches the page. Run from the repository root:
//   node docs/article-work/indexes/build-experiment.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const here = (file) => new URL(file, import.meta.url);
const page = readFileSync(here('../../../src/lib/sql-lessons/indexes.ts'), 'utf8');
const s = Object.fromEntries([...page.matchAll(/const (\w+) = `([\s\S]*?)`;/g)].map((m) => [m[1], m[2]]));
const plan = (sql) => 'EXPLAIN (ANALYZE, BUFFERS)\n' + sql;

writeFileSync(here('./experiment.sql'), [
  `-- Indexes: the complete experiment from the article. PostgreSQL 18.
-- Run in a fresh session. Every write affects a temporary table that
-- disappears when the session ends. Use psql -f, or run the statements one
-- at a time in a query editor with autocommit on: VACUUM cannot run inside
-- a transaction block. EXPLAIN ANALYZE executes its statement.`,
  readFileSync(here('./setup.sql'), 'utf8').trim(),
  '-- Sequential scan: no index on customer_id yet. The second query is the\n-- history query, used again in later sections.',
  plan(s.lookup),
  plan(s.history),
  '-- Index entries and TIDs: an index on customer_id.',
  s.customerIndex,
  plan(s.lookup),
  '-- Range scans.',
  plan(s.range),
  '-- Selectivity: try other bounds too, such as 550.',
  plan(s.wideRange),
  '-- Selectivity belongs to the value: paid is 80% of the orders, pending 20%.\n-- Then the paid orders again with the preferred routes turned off.',
  s.statusIndex,
  plan(s.paidOrders),
  plan(s.pendingOrders),
  s.forceIndex,
  plan(s.paidOrders),
  s.resetPlanner,
  '-- Combining two indexes, one condition selective enough to need no\n-- second index, and an OR whose second branch has no index.',
  plan(s.bothConditions),
  plan(s.selectiveAnd),
  plan(s.eitherCondition),
  plan(s.unindexedBranch),
  s.dropStatus,
  '-- Composite indexes: the history query with the customer index, then\n-- with the reversed index, then with the composite index.',
  plan(s.history),
  s.reversedIndex,
  plan(s.history),
  s.compositeIndex,
  plan(s.history),
  '-- Covering indexes and index-only scans: before VACUUM, after it, and\n-- after an update to another order on the same table page.',
  s.coveringIndex,
  plan(s.history),
  'VACUUM (ANALYZE) index_orders;',
  plan(s.history),
  `SELECT pg_relation_size('index_orders') AS table_bytes,
       pg_relation_size('index_orders_cover') AS covering_index_bytes;`,
  s.neighbourUpdate,
  plan(s.history),
  '-- Checking an index with EXPLAIN: a condition the index cannot use.',
  plan(s.residual),
  '-- Partial and expression indexes.',
  s.partialIndex,
  plan(s.pending),
  s.dayIndex,
  plan(s.day),
  plan(s.dayCast),
  '-- Page splits: the primary key with its keys inserted in random order.',
  s.randomKeys,
  '-- Deleted rows: a copy with two rows in three deleted, before and after\n-- VACUUM and REINDEX.',
  s.thinned,
  s.thinnedSize,
  'VACUUM thinned;',
  s.thinnedSize,
  s.rebuildThinned,
  s.thinnedSize,
  '-- The leading column has no condition: only (customer_id, placed_at)\n-- remains, as a unique index. Then the same window for one customer it\n-- contains, the window with an index on placed_at, and the order the\n-- unique index can and cannot supply.',
  s.leadingIndex,
  s.uniqueIndex,
  plan(s.leading),
  plan(s.leadingCustomer),
  s.placedIndex,
  plan(s.leading),
  plan(s.mixedOrder),
  plan(s.wholeOrder),
  '-- The column wrapped in a function.',
  s.emailIndex,
  plan(s.email),
  plan(s.lowerEmail),
  '-- Finding unused indexes: scans per index so far. Counts can lag behind\n-- the session that made them.',
  s.usage,
  '-- Statistics that no longer match the data: a separate pair of tables.\n-- Autovacuum never processes temporary tables, so nothing refreshes the\n-- statistics until ANALYZE runs.',
  s.staleSetup,
  plan(s.staleNew),
  plan(s.staleJoin),
  s.analyzeEvents,
  plan(s.staleNew),
  plan(s.staleJoin),
  '-- End the session to remove the temporary tables.',
].join('\n\n') + '\n');
