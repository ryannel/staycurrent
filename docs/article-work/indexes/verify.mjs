import { PGlite } from '@electric-sql/pglite';
import { readFileSync, writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const db = new PGlite();
await db.exec(readFileSync(new URL('./setup.sql', import.meta.url), 'utf8'));
const source=readFileSync(new URL('../../../src/pages/learn/databases/relational/indexes.astro',import.meta.url),'utf8');
const snippets=Object.fromEntries([...source.matchAll(/const (\w+) = `([\s\S]*?)`;/g)].map(m=>[m[1],m[2]]));
const query=snippets.history;
const explain = async (sql) => (await db.query('EXPLAIN (ANALYZE, BUFFERS, TIMING OFF, FORMAT JSON) ' + sql)).rows[0]['QUERY PLAN'][0];
const stages=[];
const capture=async(name)=>{
 const rows=(await db.query(query)).rows;
 assert.deepEqual(rows.map(r=>r.order_id),[59041,58041,57041,56041,55041,54041,53041,52041,51041,50041]);
 stages.push({name,rows,plan:await explain(query)});
};
await capture('primary key only');
await db.exec('CREATE INDEX index_orders_customer ON index_orders (customer_id)');
await capture('customer only');
await db.exec('DROP INDEX index_orders_customer; CREATE INDEX index_orders_history ON index_orders (customer_id, placed_at DESC, order_id DESC)');
await capture('ordered composite');
const filtered=await explain(snippets.residual);
await db.exec('DROP INDEX index_orders_history; CREATE INDEX index_orders_cover ON index_orders (customer_id, placed_at DESC, order_id DESC) INCLUDE (total)');
await capture('cover before vacuum');
await db.exec('VACUUM (ANALYZE) index_orders');
await capture('cover after vacuum');
const broad=await explain('SELECT sum(total) FROM index_orders WHERE customer_id BETWEEN 1 AND 900');
const sizes=(await db.query("SELECT pg_relation_size('index_orders') AS table_bytes, pg_relation_size('index_orders_cover') AS covering_index_bytes")).rows[0];
const version=(await db.query('SELECT version()')).rows[0].version;
const nodes=(plan)=>[plan,...(plan.Plans??[]).flatMap(nodes)];
assert.equal(nodes(stages[0].plan.Plan).find(n=>n['Node Type']==='Seq Scan')['Rows Removed by Filter'],59985);
assert.equal(nodes(stages[1].plan.Plan).find(n=>n['Node Type']==='Bitmap Heap Scan')['Rows Removed by Filter'],45);
assert.equal(nodes(stages[1].plan.Plan).find(n=>n['Node Type']==='Bitmap Index Scan')['Actual Rows'],60);
assert(!nodes(stages[2].plan.Plan).some(n=>n['Node Type']==='Sort'));
assert.equal(nodes(stages[2].plan.Plan).find(n=>n['Node Type']==='Index Scan')['Actual Rows'],10);
assert.equal(nodes(filtered.Plan).find(n=>n['Node Type']==='Index Scan')['Rows Removed by Filter'],2);
assert.equal(nodes(stages[3].plan.Plan).find(n=>n['Node Type']==='Index Only Scan')['Heap Fetches'],10);
assert.equal(nodes(stages[4].plan.Plan).find(n=>n['Node Type']==='Index Only Scan')['Heap Fetches'],0);
assert.equal(nodes(broad.Plan).find(n=>n['Node Type']==='Index Only Scan')['Actual Rows'],54000);
await db.exec(snippets.writes);
assert.equal((await db.query('SELECT count(*) AS n FROM index_orders')).rows[0].n,60900);
assert.equal((await db.query('SELECT count(*) AS n FROM index_orders WHERE order_id BETWEEN 60001 AND 60200 AND total=26.00')).rows[0].n,200);
const afterWrites={rows:(await db.query(query)).rows,plan:await explain(query),sizes:(await db.query("SELECT pg_relation_size('index_orders') AS table_bytes,pg_relation_size('index_orders_cover') AS covering_index_bytes")).rows[0]};
assert.equal(afterWrites.rows[0].order_id,60041);
// Execute the actual downloadable script in a new session, including its DO assertions.
const downloadDb=new PGlite();
// VACUUM cannot run in a transaction block: split the one multi-statement call here.
const download=readFileSync(new URL('./experiment.sql',import.meta.url),'utf8').split('VACUUM (ANALYZE) index_orders;');
await downloadDb.exec(download[0]);
await downloadDb.exec('VACUUM (ANALYZE) index_orders');
await downloadDb.exec(download[1]);
assert.equal((await downloadDb.query('SELECT count(*) AS n FROM index_orders')).rows[0].n,60900);
await downloadDb.close();
await db.close();
writeFileSync(new URL('./observed.json',import.meta.url),JSON.stringify({checked:'2026-10-15',runtime:'PGlite 0.5.8, in-memory; no storage or server latency benchmark',version,stages,filtered,broad,sizes,afterWrites},null,2)+'\n');
console.log('Verified five equivalent history results, scan/sort/filter counts, covering visibility, broad scan, writes and the complete downloadable script on '+version.split(' on ')[0]);
