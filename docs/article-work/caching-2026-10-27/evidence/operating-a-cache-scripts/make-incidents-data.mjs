// Turns the four measured recordings (operating-a-cache-data/*.jsonl) into the
// compact module Figure 4 replays. Usage, from the repository root:
//   node docs/article-work/caching-2026-10-27/evidence/operating-a-cache-scripts/make-incidents-data.mjs
import fs from 'node:fs';
const dataDir = 'docs/article-work/caching-2026-10-27/evidence/operating-a-cache-data';
const out = 'src/components/caching/operating-a-cache/incidents-data.mjs';
const FROM = 140, TO = 420; // seconds of each recording kept; the incident is at 240
const scenarios = {};
for (const s of ['small', 'ttl', 'rename', 'flush']) {
  const rows = fs.readFileSync(`${dataDir}/${s}.jsonl`, 'utf8').trim().split('\n').map(line => JSON.parse(line));
  const kept = rows.filter(r => r.t >= FROM && r.t <= TO);
  scenarios[s] = {
    hits: kept.map(r => r.keyspace_hits),
    misses: kept.map(r => r.keyspace_misses),
    evicted: kept.map(r => r.evicted_keys),
    expired: kept.map(r => r.expired_keys),
    keys: kept.map(r => r.keys),
    memory: kept.map(r => Math.round(r.used_memory / 1024)),
  };
}
const text = `// Generated by docs/article-work/caching-2026-10-27/evidence/operating-a-cache-scripts/make-incidents-data.mjs
// from measurements on Redis 8.10.3 (evidence/operating-a-cache.txt, section E8). Do not edit by hand.
// Each array holds one INFO reading a second, from ${FROM} s to ${TO} s of a recording; the incident is at 240 s.
// hits, misses, evicted and expired are INFO's cumulative counters; keys is DBSIZE; memory is used_memory in KiB.
export const FROM = ${FROM};
export const INCIDENT = 240;
export const RECORDINGS = ${JSON.stringify(scenarios)};
`;
fs.writeFileSync(out, text);
console.log('wrote', out, text.length, 'bytes');
