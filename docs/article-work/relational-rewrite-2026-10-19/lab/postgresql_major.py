#!/usr/bin/env python3
"""Disposable 17.6 -> 18.6 copy-mode pg_upgrade, not an extension inventory."""
import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile

WORK = Path(__file__).resolve().parents[1]
OLD = Path('/private/tmp/staycurrent-pg17/bin')
NEW = Path('/opt/homebrew/opt/postgresql@18/bin')
root = Path(tempfile.mkdtemp(prefix='staycurrent-pg-major-'))
records = []

def run(label, args, check=True):
    result = subprocess.run([str(x) for x in args], cwd=root,
                            capture_output=True, text=True, timeout=180)
    records.append(dict(label=label, command=[str(x) for x in args],
                        exit=result.returncode, stdout=result.stdout,
                        stderr=result.stderr))
    (WORK/'evidence/rl122-major-observed.json').write_text(json.dumps({
        'scope': 'Native macOS ARM64; 17.6 compiled from official source; 18.6 Homebrew. Copy mode, libc C/UTF8, checksums enabled, no optional extension. Disposable isolated clusters.',
        'records': records}, indent=2)+'\n')
    print(label, result.returncode, flush=True)
    if check and result.returncode:
        raise RuntimeError(result.stderr)
    return result

def sql(label, port, statement, check=True):
    return run(label,[NEW/'psql','-X','-v','ON_ERROR_STOP=1','-h',root,
                      '-p',str(port),'-U','lab','-d','postgres','-At','-c',statement],check)

try:
    for name, binary in [('old',OLD),('new',NEW)]:
        run(name+'-version',[binary/'postgres','--version'])
        run(name+'-init',[binary/'initdb','-D',root/name,'-U','lab','-A','trust',
                         '--no-locale','-E','UTF8','--data-checksums'])
    run('source-start',[OLD/'pg_ctl','-D',root/'old','-l',root/'old.log','-o',
                       f"-p 56931 -k {root} -c listen_addresses=''",'-w','start'])
    sql('source-seed',56931,"CREATE TABLE orders(tenant text, request text, price numeric(10,2) CHECK(price>=0), seq bigint GENERATED BY DEFAULT AS IDENTITY, PRIMARY KEY(tenant,request)); INSERT INTO orders(tenant,request,price) VALUES('t4','r81',20),('t4','r82',25); SELECT count(*),sum(price) FROM orders; CREATE ROLE booking_app LOGIN; GRANT SELECT,INSERT ON orders TO booking_app; GRANT USAGE ON SEQUENCE orders_seq_seq TO booking_app")
    run('source-stop',[OLD/'pg_ctl','-D',root/'old','-m','fast','-w','stop'])
    upgrade=[NEW/'pg_upgrade','--old-bindir',OLD,'--new-bindir',NEW,
             '--old-datadir',root/'old','--new-datadir',root/'new',
             '--old-port','56931','--new-port','56932','--username','lab',
             '--socketdir',root]
    run('binary-compatibility-check',upgrade+['--check'])
    run('copy-mode-upgrade',upgrade)
    run('target-start',[NEW/'pg_ctl','-D',root/'new','-l',root/'new.log','-o',
                       f"-p 56932 -k {root} -c listen_addresses=''",'-w','start'])
    sql('target-maintenance',56932,'ANALYZE')
    sql('target-original-contract',56932,'SELECT version(); SELECT request,price,seq FROM orders ORDER BY request; SELECT count(*),sum(price) FROM orders')
    sql('target-application-acceptance',56932,"SET ROLE booking_app; INSERT INTO orders(tenant,request,price) VALUES('t4','r83',30) RETURNING seq; SELECT count(*),sum(price) FROM orders")
    sql('target-duplicate-rejected',56932,"INSERT INTO orders(tenant,request,price) VALUES('t4','r81',20)",False)
    sql('target-negative-rejected',56932,"INSERT INTO orders(tenant,request,price) VALUES('t4','r84',-1)",False)
    # Copy mode leaves independent old files. Reopening here is isolated inspection,
    # with no application routing, to expose why they are no longer current.
    run('retained-source-start',[OLD/'pg_ctl','-D',root/'old','-l',root/'old.log','-o',
                                f"-p 56931 -k {root} -c listen_addresses=''",'-w','start'])
    sql('retained-source-misses-r83',56931,'SELECT request,price FROM orders ORDER BY request; SELECT count(*),sum(price) FROM orders')
finally:
    for name,binary in [('old',OLD),('new',NEW)]:
        subprocess.run([str(binary/'pg_ctl'),'-D',str(root/name),'-m','immediate','stop'],capture_output=True)
    shutil.rmtree(root)
